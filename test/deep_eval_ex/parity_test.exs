defmodule DeepEvalEx.ParityTest do
  @moduledoc """
  Compares DeepEvalEx's test run exports with files written by deepeval
  4.3.1 for the same inputs.

  Each scenario in `test/fixtures/deepeval/<scenario>/` holds `input.json`
  (test cases, metrics, identifier and hyperparameters) and the
  `test_run.json` deepeval wrote for it, generated by
  `scripts/parity/generate_fixtures.py` (see the README there). The test
  runs the same inputs through `DeepEvalEx.evaluate_run/3`, reads the file
  it writes and compares it with deepeval's: key sets and key order, value
  types (integer vs float included), values, and finally the raw bytes.

  Only values proven nondeterministic are normalised, in both files:

  - the run-level `runDuration`, the wall-clock time of the whole run

  Test-case `runDuration` is not normalised: deepeval's async executor
  records any test case that took under a second as the integer `0`, which
  these instantaneous metrics always do.

  JSON objects inside test cases (`metadata`, tool calls'
  `inputParameters` and `output`) are passed in as `Jason.OrderedObject`s,
  as Elixir maps do not keep Python's insertion order.
  """

  use ExUnit.Case, async: true

  import ExUnit.CaptureLog

  alias DeepEvalEx.Metrics.ExactMatch
  alias DeepEvalEx.Test.JSONDiff
  alias DeepEvalEx.Test.ParityMetrics.{Failing, Stub}
  alias DeepEvalEx.TestCase
  alias Jason.OrderedObject

  @moduletag :parity
  @moduletag :tmp_dir

  @fixtures Path.expand("../fixtures/deepeval", __DIR__)
  # scripted/ holds the scripted-judge scenarios of ScriptedParityTest,
  # prompts/ the prompt goldens of PromptGoldenTest.
  @scenarios @fixtures
             |> File.ls!()
             |> Enum.reject(&(&1 in ["prompts", "scripted"]))
             |> Enum.filter(&File.dir?(Path.join(@fixtures, &1)))
             |> Enum.sort()

  for scenario <- @scenarios, file <- ["input.json", "test_run.json"] do
    @external_resource Path.join([@fixtures, scenario, file])
  end

  test "covers every scenario of the fixture script" do
    assert @scenarios ==
             Enum.sort(~w(exact_match hyperparameters llm_metric metric_error rag_and_tools))
  end

  for scenario <- @scenarios do
    describe "#{scenario} scenario" do
      @describetag scenario: scenario

      test "has deepeval's keys, key order, value types and values", ctx do
        {ours, theirs} = exports(ctx)

        assert JSONDiff.diff(decode(ours), decode(theirs)) == []
      end

      test "has deepeval's metricsScores, testPassed, testFailed and order", ctx do
        {ours, theirs} = exports(ctx)
        ours = decode(ours)
        theirs = decode(theirs)

        for key <- ~w(metricsScores testPassed testFailed) do
          assert get(ours, key) == get(theirs, key), "#{key} differs"
        end

        assert orders(ours) == orders(theirs)
      end

      test "is byte for byte deepeval's file", ctx do
        {ours, theirs} = exports(ctx)

        assert ours == theirs
      end
    end
  end

  # Runs the scenario through DeepEvalEx and returns {ours, deepeval's}, both
  # normalised.
  defp exports(%{scenario: scenario, tmp_dir: tmp_dir}) do
    dir = Path.join(@fixtures, scenario)
    input = dir |> Path.join("input.json") |> File.read!() |> decode()

    opts =
      [
        results_folder: tmp_dir,
        identifier: get(input, "identifier"),
        hyperparameters: hyperparameters(get(input, "hyperparameters"))
      ]
      |> Enum.reject(fn {_key, value} -> is_nil(value) end)

    {{_results, _test_run, path}, _log} =
      with_log(fn ->
        DeepEvalEx.evaluate_run(
          Enum.map(get(input, "test_cases"), &test_case/1),
          Enum.map(get(input, "metrics"), &metric/1),
          opts
        )
      end)

    assert is_binary(path), "DeepEvalEx wrote no test run file"

    {normalise(File.read!(path)), normalise(File.read!(Path.join(dir, "test_run.json")))}
  end

  # The run-level runDuration is the only key following testFailed.
  defp normalise(json) do
    String.replace(json, ~r/("testFailed": \d+, "runDuration": )[^,}]+/, "\\1\"<normalised>\"")
  end

  defp decode(json), do: Jason.decode!(json, objects: :ordered_objects)

  defp get(%OrderedObject{} = object, key), do: object[key]

  defp hyperparameters(nil), do: nil
  defp hyperparameters(%OrderedObject{values: pairs}), do: pairs

  # The test case's own fields as a map; nested JSON objects stay ordered.
  defp test_case(%OrderedObject{values: pairs}) do
    pairs
    |> Map.new(fn
      {key, tool_calls} when key in ["tools_called", "expected_tools"] ->
        {key, Enum.map(tool_calls, &Map.new(&1.values))}

      pair ->
        pair
    end)
    |> TestCase.new!()
  end

  defp metric(spec) do
    case get(spec, "kind") do
      "exact_match" ->
        ExactMatch

      "stub" ->
        %Stub{
          name: get(spec, "name"),
          score: get(spec, "score"),
          reason: get(spec, "reason"),
          threshold: get(spec, "threshold"),
          evaluation_model: get(spec, "evaluation_model"),
          evaluation_cost: get(spec, "evaluation_cost"),
          input_tokens: get(spec, "input_tokens"),
          output_tokens: get(spec, "output_tokens")
        }

      "error" ->
        %Failing{
          name: get(spec, "name"),
          threshold: get(spec, "threshold"),
          exception: get(spec, "exception"),
          message: get(spec, "message")
        }
    end
  end

  defp orders(export) do
    export |> get("testCases") |> Enum.map(&{get(&1, "name"), get(&1, "order")})
  end
end
