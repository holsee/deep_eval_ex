defmodule DeepEvalEx.Prompts.JsonCorrectness do
  @moduledoc """
  Prompt template for the JsonCorrectness metric.

  JsonCorrectness checks that an LLM's output is JSON matching an expected
  schema. The check is made in code; the judge only explains a failure.

  `generate_reason/1` renders deepeval 4.3.1's `JsonCorrectnessMetric`
  template of the same name byte for byte, as deepeval renders it for a
  text-only test case. 4.3.1's template includes the multimodal input rules
  fragment unconditionally, so the prompt carries it too. The schema is
  printed as deepeval prints its pydantic model's `model_json_schema()`,
  with `json.dumps(indent=4)` (`format_expected_schema/1`), and the
  validity as a Python bool. JsonCorrectness has no System One templates.
  """

  alias DeepEvalEx.Prompts.Python
  alias DeepEvalEx.TestRun.JSON

  @doc """
  Generates a prompt asking why the output is, or is not, valid JSON for
  the expected schema.

  ## Options

  - `:actual_output` - the generated JSON (required)
  - `:expected_schema` - the JSON Schema it was checked against, a map or a
    `Jason.OrderedObject` (required)
  - `:is_valid_json` - whether it matched (required); deepeval only asks
    when it did not
  """
  def generate_reason(opts) do
    actual_output = Keyword.fetch!(opts, :actual_output)
    expected_schema = opts |> Keyword.fetch!(:expected_schema) |> format_expected_schema()
    is_valid_json = opts |> Keyword.fetch!(:is_valid_json) |> Python.repr()

    """
    Based on the given generated json, generated by an LLM, and a boolean stating whether it is a valid JSON based on the expected json schema, give a reason why it is OR is not a valid Json.


    --- MULTIMODAL INPUT RULES ---
    - Treat image content as factual evidence.
    - Only reference visual details that are explicitly and clearly visible.
    - Do not infer or guess objects, text, or details not visibly present.
    - If an image is unclear or ambiguous, mark uncertainty explicitly.


    ** 
    IMPORTANT: Please make sure to only return in JSON format, with the 'reason' key providing the reason.
    Example JSON:
    {
      "reason": "The generated Json is <is_valid_json> because <your_reason>."
    }

    If the json is not a valid one, your reason MUST compare `Expected Json Schema` and `Generated Json` in your reason. Keep it SHORT and CONCISE while being very FACTUAL and ACTIONABLE.
    **

    Generated Json:
    #{actual_output}

    Expected Json Schema:
    #{expected_schema}

    Is Valid Json?
    #{is_valid_json}

    JSON:\
    """
  end

  @doc """
  Formats a JSON Schema as deepeval prints its expected schema,
  `serialize_to_json(model_json_schema(), indent=4)`: Python's
  `json.dumps(indent=4)`, non-ASCII escaped. A `Jason.OrderedObject` keeps
  its key order; a map prints in map order.

  ## Examples

      iex> DeepEvalEx.Prompts.JsonCorrectness.format_expected_schema(%{"type" => "string"})
      ~s({\\n    "type": "string"\\n})
  """
  @spec format_expected_schema(map() | Jason.OrderedObject.t()) :: String.t()
  def format_expected_schema(schema), do: JSON.encode!(schema, indent: 4)
end
